# SUBMIT STOCK FOR ADMIN APPROVAL

def submit_stock_for_approval():

    if not st.session_state.stock_items:

        st.error("Please add at least one stock item.")

        return

    # Use the shared PostgreSQL engine from database.database

    try:

        cash_in_hand, cash_in_bank = get_available_funds()

        available_funds = cash_in_hand + cash_in_bank

        total_purchase_value = sum(

            item["PurchaseValue"] for item in st.session_state.stock_items

        )

        if available_funds <= total_purchase_value:

            st.error(

                "Cannot submit this stock entry: combined cash and bank balance "

                f"(₹{available_funds:,.2f}) must be greater than the purchase "

                f"value (₹{total_purchase_value:,.2f})."

            )

            return



        with engine.begin() as conn:

            # Create Manager Stock Entry

            header_sql = text("""

                INSERT INTO "ManagerStockEntry"

                (

                    "EnteredBy",

                    "TotalPurchaseValue",

                    "Status"

                )

VALUES

                (

                    :entered_by,

                    :total_purchase_value,

                    'PENDING'

                )

RETURNING "ManagerStockEntryID"

            """)

            result = conn.execute(

                header_sql,

                {

                    "entered_by": int(user["UserID"]),

                    "total_purchase_value": total_purchase_value,

                },

            )

            manager_stock_entry_id = result.scalar_one()

            # Insert each stock item

            item_sql = text("""

                INSERT INTO "ManagerStockEntryItems"

                (

                    "ManagerStockEntryID",

                    "ProductID",

                    "ProductName",

                    "Barcode",

                    "BatchNo",

                    "Quantity",

                    "PurchasePrice",

                    "SellingPrice",

                    "ExpiryDate",

                    "PurchaseValue",

                    "ProductStatus"

                )

                VALUES

                (

                    :entry_id,

                    :product_id,

                    :product_name,

                    :barcode,

                    :batch_no,

                    :quantity,

                    :purchase_price,

                    :selling_price,

                    :expiry_date,

                    :purchase_value,

                    :product_status

                )

            """)

            for item in st.session_state.stock_items:

                conn.execute(

                    item_sql,

                    {

                        "entry_id": manager_stock_entry_id,

                        "product_id": item["ProductID"],

                        "product_name": item["ProductName"],

                        "barcode": item["Barcode"],

                        "batch_no": item["BatchNo"],

                        "quantity": item["Quantity"],

                        "purchase_price": item["PurchasePrice"],

                        "selling_price": item["SellingPrice"],

                        "expiry_date": item["ExpiryDate"],

                        "purchase_value": item["PurchaseValue"],

                        "product_status": item["ProductStatus"],

                    },

                )

        # Clear current stock entry after successful commit

        st.session_state.stock_items = []

        st.success(

            f"✅ Stock submitted successfully. " f"Entry No: {manager_stock_entry_id}"

        )

        st.info("The stock is now PENDING Admin approval.")

    except Exception as e:

        st.error("Unable to submit stock entry.")

        st.exception(e)





