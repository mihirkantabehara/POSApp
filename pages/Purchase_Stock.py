def get_available_funds():

    with engine.begin() as conn:

        conn.execute(text("""

                CREATE TABLE IF NOT EXISTS "BankTransactions" (

                    "BankTransactionID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                    "CashDrawerID" BIGINT NULL,

                    "UserID" BIGINT NOT NULL,

                    "TransactionType" VARCHAR(50) NOT NULL,

                    "Amount" NUMERIC(18, 2) NOT NULL CHECK ("Amount" > 0),

                    "Reason" VARCHAR(500),

                    "TransactionDateTime" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP

                )

            """))

        balances = conn.execute(text("""

                WITH drawers AS (

                    SELECT DISTINCT ON ("UserID")

                        "CashDrawerID",

                        "UserID",

                        "OpenDateTime",

                        "OpeningCash"

                    FROM "CashDrawers"

                    WHERE "Status" = 'Open'

                    ORDER BY "UserID", "CashDrawerID" DESC

                ),

                drawer_balances AS (

                    SELECT

                        COALESCE(

                            d."OpeningCash"

                            + COALESCE((

                                SELECT SUM(s."GrandTotal")

                                FROM "Sales" AS s

                                WHERE s."UserID" = d."UserID"

                                  AND s."PaymentMode" = 'Cash'

                                  AND s."SaleDate" >= d."OpenDateTime"

                            ), 0)

                            + COALESCE((

                                SELECT SUM(

                                    CASE

                                        WHEN ct."TransactionType" = 'Cash In'

                                            THEN ct."Amount"

                                        ELSE -ct."Amount"

                                    END

                                )

                                FROM "CashTransactions" AS ct

                                WHERE ct."CashDrawerID" = d."CashDrawerID"

                                  AND ct."TransactionType" IN ('Cash In', 'Expense', 'Cash Out')

                            ), 0),

                            0

                        ) AS "CashInHand",

                        GREATEST(

                            0,

                            COALESCE((

                                SELECT SUM(s."GrandTotal")

                                FROM "Sales" AS s

                                WHERE s."UserID" = d."UserID"

                                  AND s."PaymentMode" IN ('UPI', 'Card')

                                  AND s."SaleDate" >= d."OpenDateTime"

                            ), 0)

                            + COALESCE((

                                SELECT SUM(

                                    CASE

                                        WHEN bt."TransactionType" = 'Bank Deposit'

                                            THEN bt."Amount"

                                        ELSE -bt."Amount"

                                    END

                                )

                                FROM "BankTransactions" AS bt

                                WHERE bt."UserID" = d."UserID"

                                  AND bt."TransactionDateTime" >= d."OpenDateTime"

                                  AND bt."TransactionType" IN ('Bank Deposit', 'Bank Withdrawal')

                            ), 0)

                        ) AS "CashInBank"

                    FROM drawers AS d

                )

                SELECT

                    COALESCE(SUM("CashInHand"), 0) AS "CashInHand",

                    COALESCE(SUM("CashInBank"), 0) AS "CashInBank"

                FROM drawer_balances

            """)).mappings().first()



    if not balances:

        return 0.0, 0.0

    return float(balances["CashInHand"]), float(balances["CashInBank"])





# FIND EXISTING PRODUCT

def find_product(barcode, product_name):

    barcode = (barcode or "").strip()

    product_name = (product_name or "").strip()

    if not barcode and not product_name:

        return None, None

    with engine.connect() as conn:

        # First check barcode

        if barcode:

            result = (

                conn.execute(

                    text("""

                    SELECT

                        "ProductID",

                        "ProductName",

                        "Barcode",

                        "SellingPrice",

                        "Stock",

                        "GSTPercent",

                        "PurchasePrice"

                    FROM "Products"

                    WHERE BTRIM("Barcode") = :barcode

                """),

                    {"barcode": barcode},

                )

                .mappings()

                .all()

            )

            if len(result) == 1:

                product = dict(result[0])

                return product, "Barcode"

            elif len(result) > 1:

                raise ValueError(f"Multiple products found with barcode " f"{barcode}.")

        # Then check product name

        if product_name:

            result = (

                conn.execute(

                    text("""

                    SELECT

                        "ProductID",

                        "ProductName",

                        "Barcode",

                        "SellingPrice",

                        "Stock",

                        "GSTPercent",

                        "PurchasePrice"

                    FROM "Products"

                    WHERE LOWER(BTRIM("ProductName"))

                        =

                          LOWER(BTRIM(:product_name))

                """),

                    {"product_name": product_name},

                )

                .mappings()

                .all()

            )

            if len(result) == 1:

                product = dict(result[0])

                return product, "Product Name"

            elif len(result) > 1:

                raise ValueError(

                    f"Multiple products found with name " f"{product_name}."

                )

    return None, None





# GENERATE TEMPORARY BATCH NUMBER

def generate_batch_number():

    now = datetime.now()

    return f"B{now.strftime('%Y%m%d%H%M%S%f')[:-3]}"





