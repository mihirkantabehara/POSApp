# ADD STOCK

def add_stock():

    barcode = st.session_state.barcode.strip()

    product_name = st.session_state.product_name.strip()

    quantity = float(st.session_state.quantity)

    purchase_price = float(st.session_state.purchase_price)

    selling_price = float(st.session_state.selling_price)

    expiry_date = st.session_state.expiry_date

    # Validation

    if not product_name:

        st.session_state.match_message = "❌ Please enter Product Name."

        return

    if quantity <= 0:

        st.session_state.match_message = "❌ Quantity must be greater than zero."

        return

    if purchase_price < 0:

        st.session_state.match_message = "❌ Purchase price cannot be negative."

        return

    if selling_price < 0:

        st.session_state.match_message = "❌ Selling price cannot be negative."

        return

    # Find existing product

    try:

        product, match_type = find_product(barcode, product_name)

    except ValueError as e:

        st.session_state.match_message = f"❌ {str(e)}"

        return

    # Existing product

    if product:

        # Existing products: if the manager leaves prices at 0,

        # use the current product prices. A manually entered non-zero

        # price is preserved because batch prices may change.

        if purchase_price <= 0 and product.get("PurchasePrice") is not None:

            purchase_price = float(product["PurchasePrice"])

        if selling_price <= 0 and product.get("SellingPrice") is not None:

            selling_price = float(product["SellingPrice"])

        product_id = product["ProductID"]

        final_product_name = product["ProductName"]

        final_barcode = product["Barcode"]

        product_status = "EXISTING"

        match_message = (

            f"✅ Existing product found by "

            f"{match_type}: "

            f"{final_product_name} "

            f"(Product ID: {product_id})"

        )

    # New product

    else:

        product_id = None

        final_product_name = product_name

        final_barcode = barcode or None

        product_status = "NEW"

        match_message = "🆕 New product. " "Admin approval will create the product."

    # Generate batch number

    batch_number = generate_batch_number()

    # Purchase value

    purchase_value = quantity * purchase_price

    # Create staging item

    item = {

        "ProductID": product_id,

        "ProductName": final_product_name,

        "Barcode": final_barcode,

        "BatchNo": batch_number,

        "Quantity": quantity,

        "PurchasePrice": purchase_price,

        "SellingPrice": selling_price,

        "ExpiryDate": expiry_date,

        "PurchaseValue": purchase_value,

        "ProductStatus": product_status,

        "MatchType": match_type or "NEW",

    }

    st.session_state.stock_items.append(item)

    st.session_state.match_message = match_message

    # Clear form

    st.session_state.barcode = ""

    st.session_state.product_name = ""

    st.session_state.quantity = 1.0

    st.session_state.purchase_price = 0.0

    st.session_state.selling_price = 0.0

    st.session_state.expiry_date = date.today()





